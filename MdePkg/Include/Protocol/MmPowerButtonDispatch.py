# } EFI_POWER_BUTTON_PHASE;
EfiPowerButtonEntry     = 1
EfiPowerButtonExit      = 2
EfiPowerButtonMax       = 3
EFI_POWER_BUTTON_PHASE  = ENUM

# 
# ///
# /// The dispatch function's context.
# ///
# typedef struct {
#   ///
